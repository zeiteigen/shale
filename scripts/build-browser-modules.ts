/**
 * Bundle every extension's `chrome_module` (see lib/extension.ts) into the Chrome extension:
 *
 *   modules/<extension>/background.js   service-worker module (default export `register`)
 *   modules/<extension>/popup.js        optional popup section (export `render`)
 *   modules/<extension>/inject/<name>.js scripts injected into pages on demand
 *   modules/registry.js, modules/popup-registry.js  static imports of the above
 *
 * MV3 service workers cannot `import()` dynamically, so the registries import statically.
 * `--check` fails when the committed output is stale.
 */
import { mkdtemp, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { isTExtensionManifest, type ChromeModuleManifest } from "../lib/extension";

const root = join(import.meta.dir, "..");
const extensionsDir = join(root, "extensions");
const outputDir = join(root, "scripts/browser-chrome-extension/modules");
const banner = (source: string) =>
  `// Generated by scripts/build-browser-modules.ts from ${source}. Do not edit.\n`;

async function chromeModules() {
  const found: Array<{ id: string; dir: string; module: ChromeModuleManifest }> = [];
  for (const entry of (await readdir(extensionsDir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const file = Bun.file(join(extensionsDir, entry.name, "manifest.json"));
    if (!(await file.exists())) continue;
    const manifest = await file.json();
    if (!manifest.chrome_module) continue;
    if (!isTExtensionManifest(manifest)) throw new Error(`Invalid manifest in extensions/${entry.name}`);
    if (!/^[a-z][a-z0-9-]*$/.test(manifest.name)) throw new Error(`Chrome module name ${manifest.name} is not a safe path segment`);
    found.push({ id: manifest.name, dir: join(extensionsDir, entry.name), module: manifest.chrome_module! });
  }
  // The browser module claims no hosts, so it goes first and other modules' claims win.
  return found.sort((a, b) => Number(b.id === "browser") - Number(a.id === "browser"));
}

async function bundle(entry: string, format: "esm" | "iife", minify: boolean) {
  const result = await Bun.build({ entrypoints: [entry], target: "browser", format, minify, root });
  if (!result.success) throw new Error(`Bundling ${relative(root, entry)} failed:\n${result.logs.join("\n")}`);
  if (result.outputs.length !== 1) throw new Error(`${relative(root, entry)} must bundle to one file`);
  return result.outputs[0]!.text();
}

/** Each injected script registers its default export under `<module>/<name>` for the core to call. */
async function bundleInject(scratch: string, id: string, name: string, entry: string) {
  const wrapper = join(scratch, `${id}-${name}.ts`);
  await Bun.write(wrapper, `import run from ${JSON.stringify(entry)};
const slots = ((globalThis as any).__shaleInjected ??= {});
slots[${JSON.stringify(`${id}/${name}`)}] = run;
`);
  return bundle(wrapper, "iife", true);
}

export async function buildBrowserModules(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const registry = { imports: [] as string[], entries: [] as string[] };
  const popups = { imports: [] as string[], entries: [] as string[] };
  const scratch = await mkdtemp(join(tmpdir(), "shale-chrome-modules-"));
  try {
    for (const [index, { id, dir, module }] of (await chromeModules()).entries()) {
      const source = (path: string) => relative(root, join(dir, path));
      files.set(`${id}/background.js`, banner(source(module.background)) + await bundle(join(dir, module.background), "esm", false));
      const inject = Object.entries(module.inject ?? {});
      for (const [name, path] of inject)
        files.set(`${id}/inject/${name}.js`, banner(source(path)) + await bundleInject(scratch, id, name, join(dir, path)));
      registry.imports.push(`import register${index} from "./${id}/background.js";`);
      registry.entries.push(`  { id: ${JSON.stringify(id)}, register: register${index}, inject: ${JSON.stringify(inject.map(([name]) => name))} },`);
      if (module.popup) {
        files.set(`${id}/popup.js`, banner(source(module.popup)) + await bundle(join(dir, module.popup), "esm", false));
        popups.imports.push(`import { render as render${index} } from "./${id}/popup.js";`);
        popups.entries.push(`  { id: ${JSON.stringify(id)}, render: render${index} },`);
      }
    }
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
  const index = ({ imports, entries }: { imports: string[]; entries: string[] }) =>
    [banner("extension manifests") + imports.join("\n"), "export default [", ...entries, "];", ""].join("\n");
  files.set("registry.js", index(registry));
  files.set("popup-registry.js", index(popups));
  return files;
}

async function existingFiles(dir: string, prefix = ""): Promise<string[]> {
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return []; }
  const files: string[] = [];
  for (const entry of entries) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await existingFiles(join(dir, entry.name), path));
    else files.push(path);
  }
  return files;
}

if (import.meta.main) {
  const files = await buildBrowserModules();
  if (process.argv.includes("--check")) {
    const stale: string[] = [];
    for (const [path, content] of files) {
      const file = Bun.file(join(outputDir, path));
      if (!(await file.exists()) || (await file.text()) !== content) stale.push(path);
    }
    for (const path of await existingFiles(outputDir)) if (!files.has(path)) stale.push(`${path} (no longer generated)`);
    if (stale.length) throw new Error(`Chrome modules are stale; run bun run browser:build\n  ${stale.join("\n  ")}`);
  } else {
    await rm(outputDir, { recursive: true, force: true });
    for (const [path, content] of files) await Bun.write(join(outputDir, path), content);
    console.log(`Built ${files.size} Chrome module file(s) into ${relative(root, outputDir)}`);
  }
}
